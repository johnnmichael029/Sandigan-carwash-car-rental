/**
 * Format a number as Philippine Peso (₱1,500.00)
 */
const formatPeso = (amount) =>
    `₱${Number(amount || 0).toLocaleString('en-PH', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

/**
 * Format a Date to a readable string in Manila timezone
 */
const formatDate = (date) => {
    if (!date) return '—';
    return new Date(date).toLocaleDateString('en-PH', {
        timeZone: 'Asia/Manila',
        year: 'numeric',
        month: 'long',
        day: 'numeric',
    });
};

/**
 * Format a datetime string (e.g., "2026-07-29T10:00") to readable form
 */
const formatBookingTime = (bookingTime) => {
    if (!bookingTime) return '—';
    try {
        const d = new Date(bookingTime);
        if (isNaN(d.getTime())) return bookingTime; // Return raw if not parseable
        return d.toLocaleString('en-PH', {
            timeZone: 'Asia/Manila',
            year: 'numeric',
            month: 'long',
            day: 'numeric',
            hour: '2-digit',
            minute: '2-digit',
            hour12: true,
        });
    } catch {
        return bookingTime;
    }
};

