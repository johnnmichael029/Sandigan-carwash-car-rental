// ─── Status Badge ────────────────────────────────────────────────────────────

const statusBadge = (status) => {
    const colors = {
        Pending:   { bg: '#1c1a0d', border: '#d97706', text: '#fbbf24' },
        Confirmed: { bg: '#0d1c14', border: '#16a34a', text: '#4ade80' },
        Cancelled: { bg: '#1c0d0d', border: '#dc2626', text: '#f87171' },
    };
    const c = colors[status] || colors.Pending;
    return `<span style="display:inline-block; background:${c.bg}; border:1px solid ${c.border};
        color:${c.text}; font-size:12px; font-weight:700; padding:4px 14px;
        border-radius:99px; letter-spacing:1px; text-transform:uppercase;">${status}</span>`;
};

// ─────────────────────────────────────────────────────────────────────────────
//  1. Car Wash Booking Confirmation
// ─────────────────────────────────────────────────────────────────────────────

const sendBookingConfirmation = async (booking) => {
    if (!booking?.emailAddress) return;

    const customerName = `${booking.firstName} ${booking.lastName}`;
    const services = Array.isArray(booking.serviceType)
        ? booking.serviceType.join(', ')
        : (booking.serviceType || '—');

    // Build discount rows if applicable
    let discountRows = '';
    if (booking.promoCode || booking.discountAmount > 0) {
        if (booking.promoCode) {
            discountRows += row('Promo Code', `<code style="background:#1e2040;padding:2px 8px;border-radius:4px;color:#a5b4fc;">${booking.promoCode}</code>`);
        }
        if (booking.promoDiscount > 0) {
            discountRows += row('Promo Discount', `<span style="color:#4ade80;">-${formatPeso(booking.promoDiscount)}</span>`);
        }
        if (booking.discountAmount > 0) {
            discountRows += row('Other Discount', `<span style="color:#4ade80;">-${formatPeso(booking.discountAmount)}</span>`);
        }
    }

    // Purchased products
    let productRows = '';
    if (Array.isArray(booking.purchasedProducts) && booking.purchasedProducts.length > 0) {
        const productList = booking.purchasedProducts
            .map(p => `${p.productName} x${p.quantity} (${formatPeso(p.price)})`)
            .join('<br/>');
        productRows = row('Add-on Products', productList);
    }

    // Home service address
    let locationRow = '';
    if (booking.serviceLocationType === 'Home Service' && booking.homeServiceDetails?.address) {
        locationRow = row('Home Service Address', booking.homeServiceDetails.address);
    }

    const content = `
      <!-- Greeting -->
      <h2 style="font-size: 22px; font-weight: 700; color: #f1f5f9; margin-bottom: 6px;">
        Booking Confirmed! 🎉
      </h2>
      <p style="font-size: 14px; color: #94a3b8; margin-bottom: 4px;">
        Hi <strong style="color:#e2e8f0;">${customerName}</strong>, thank you for booking with Sandigan!
      </p>
      <p style="font-size: 14px; color: #94a3b8; margin-bottom: 24px;">
        Your car wash booking has been received and is currently <strong style="color:#fbbf24;">pending confirmation</strong>.
        We'll take care of your vehicle!
      </p>

      ${receiptBadge(booking.batchId, 'Booking Reference ID')}

      <!-- Details Table -->
      <table class="details-table" width="100%" cellpadding="0" cellspacing="0"
        style="border-radius:10px; overflow:hidden; border:1px solid #2d2d3f; margin-bottom: 24px;">
        ${row('Status', statusBadge('Pending'))}
        ${row('Customer Name', customerName)}
        ${row('Phone Number', booking.phoneNumber || '—')}
        ${row('Vehicle Type', booking.vehicleType || '—')}
        ${row('Service(s)', services)}
        ${row('Preferred Date & Time', formatBookingTime(booking.bookingTime))}
        ${row('Service Type', booking.serviceLocationType || 'In-Store')}
        ${locationRow}
        ${productRows}
        ${discountRows}
        ${row('Total Amount', `<strong style="font-size:16px;color:#a5b4fc;">${formatPeso(booking.totalPrice)}</strong>`)}
      </table>

      <p style="font-size: 13px; color: #64748b; line-height: 1.7; background:#13131c;
          border-left: 3px solid #6366f1; padding: 12px 16px; border-radius: 0 8px 8px 0;">
        ℹ️ Your booking is <strong style="color:#fbbf24;">pending</strong> — our team will review it and confirm your slot shortly.
        You may reach out to us if you need to make any changes.
      </p>
    `;

    const html = wrapInShell(content,
        `Your booking ${booking.batchId} has been received. Thank you, ${booking.firstName}!`
    );

    try {
        await transporter.sendMail({
            from: process.env.EMAIL_FROM,
            to: booking.emailAddress,
            subject: `Booking Confirmed — ${booking.batchId} | Sandigan Car Wash`,
            html,
        });
        console.log(`✅ [Email] Booking confirmation sent to ${booking.emailAddress} (${booking.batchId})`);
    } catch (err) {
        console.error(`❌ [Email] Failed to send booking confirmation to ${booking.emailAddress}:`, err.message);
        // Non-critical — do NOT re-throw
    }
};

